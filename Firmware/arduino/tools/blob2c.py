#!/usr/bin/env python3
"""Turn the loader .bin into a C++ source placing it in the .sketch_boot section.

Usage: blob2c.py <loader.bin> <out.cpp>
Pads with 0xFF to 0x4000 bytes; fails if the bin is larger.
"""
import sys
import zlib

BLOB_LEN = 0x4000


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    data = open(argv[1], "rb").read()
    if len(data) > BLOB_LEN:
        print("error: loader is %d bytes, limit %d" % (len(data), BLOB_LEN), file=sys.stderr)
        return 1
    crc = zlib.crc32(data) & 0xFFFFFFFF
    blob = data + b"\xff" * (BLOB_LEN - len(data))
    lines = []
    for i in range(0, BLOB_LEN, 16):
        lines.append("  " + ", ".join("0x%02X" % b for b in blob[i:i + 16]) + ",")
    with open(argv[2], "w") as f:
        f.write("// GENERATED by tools/blob2c.py - do not edit.\n")
        f.write("// Loader .bin: %d bytes, crc32 %08X (padded with 0xFF to 0x%X).\n" % (len(data), crc, BLOB_LEN))
        f.write("// Regenerate: Firmware/arduino/build.sh FramLoader\n")
        f.write('#include "wpm_loader_blob.h"\n\n')
        f.write("const uint8_t wpm_loader_blob[0x4000] __attribute__((section(\".sketch_boot\"))) = {\n")
        f.write("\n".join(lines))
        f.write("\n};\n")
    print("blob2c: %d bytes, crc32 %08X -> %s" % (len(data), crc, argv[2]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
